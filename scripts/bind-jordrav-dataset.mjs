import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
const sourceRules=JSON.parse(await fs.readFile(new URL('../data/jordrav/model-rules.json',import.meta.url),'utf8'));
assert.match(sourceRules.modelVersion,/^\d+\.\d+\.\d+-prototype$/);
const folder=`prototype-${sourceRules.modelVersion.split('-')[0]}`;
const base=new URL(`../data/jordrav/${folder}/`,import.meta.url);
const bytes=await fs.readFile(new URL('manifest.json',base));
const sha=value=>createHash('sha256').update(value).digest('hex');
const manifest=JSON.parse(bytes);
assert.equal(manifest.modelVersion,sourceRules.modelVersion);
assert.equal(manifest.schemaVersion,1);
assert.equal(manifest.tiles.length,192);
assert.equal(manifest.overview.file,'overview.geojson.gz');
assert.equal(manifest.catalog.file,'catalog.json.gz');
assert.equal(manifest.rules.file,'rules.json');
for(const entry of [manifest.overview,manifest.catalog,manifest.rules,...manifest.tiles]) {
  assert.match(entry.file,/^(?:overview\.geojson\.gz|catalog\.json\.gz|rules\.json|tile-\d+-\d+\.geojson\.gz)$/);
  const payload=await fs.readFile(new URL(entry.file,base));
  assert.equal(payload.length,entry.bytes,entry.file);
  assert.equal(sha(payload),entry.sha256,entry.file);
}
const packagedRules=JSON.parse(await fs.readFile(new URL(manifest.rules.file,base),'utf8'));
assert.deepEqual(packagedRules,sourceRules,'Packaged model rules differ from source rules');
assert.match(manifest.modelVersion,/^\d+\.\d+\.\d+-prototype$/);
const code=`// Immutable public dataset identity; generated by scripts/bind-jordrav-dataset.mjs.\nexport const MODEL_VERSION = ${JSON.stringify(manifest.modelVersion)};\nexport const MANIFEST_SHA256 = '${sha(bytes)}';\nexport const DATA_BASE = new URL('../../data/jordrav/${folder}/', import.meta.url);\n`;
await fs.writeFile(new URL('../js/jordrav/dataset-binding.js',import.meta.url),code);
console.log(JSON.stringify({bound:true,modelVersion:manifest.modelVersion,manifestSha256:sha(bytes),tiles:manifest.tiles.length}));
