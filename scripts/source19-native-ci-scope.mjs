export function source19NativeCiRequired(changedPaths) {
  if (!Array.isArray(changedPaths) || changedPaths.length > 20000)
    throw new Error('SOURCE19_CI_CHANGED_PATHS_INVALID');
  const unique = new Set();
  for (const file of changedPaths) {
    if (typeof file !== 'string' || file.length < 1 || file.length > 4096
      || /[\u0000-\u001f\\]/.test(file) || file.startsWith('/')
      || path.posix.normalize(file) !== file || file === '..' || file.startsWith('../')
      || unique.has(file)) throw new Error('SOURCE19_CI_CHANGED_PATH_INVALID');
    unique.add(file);
  }
  return changedPaths.some(file => SOURCE19_NATIVE_SCOPE_PATHS.includes(file)
    || SOURCE19_NATIVE_SCOPE_DIRECTORIES.some(row => path.posix.dirname(file) === row.directory
      && row.suffixes.some(suffix => file.endsWith(suffix))));
}

export function source19NativeValidationAllowed(scopeResult, required, nativeResult) {
  return scopeResult === 'success' && ((required === 'true' && nativeResult === 'success')
    || (required === 'false' && nativeResult === 'skipped'));
}

async function main() {
  const head = process.env.SOURCE19_PR_HEAD_SHA, base = process.env.SOURCE19_PR_BASE_SHA;
  if (!/^[a-f0-9]{40}$/.test(head ?? '') || !/^[a-f0-9]{40}$/.test(base ?? '')
    || typeof process.env.GITHUB_OUTPUT !== 'string' || !process.env.GITHUB_OUTPUT)
    throw new Error('SOURCE19_CI_IDENTITY_REQUIRED');
  const git = args => execFileSync('git', args, {encoding:'utf8', maxBuffer:8*1024*1024, timeout:30000});
  if (git(['rev-parse','HEAD^{commit}']).trim() !== head)
    throw new Error('SOURCE19_CI_HEAD_MISMATCH');
  const raw = git(['diff','--name-only','--no-renames','-z',base+'...'+head,'--']);
  if (raw !== '' && !raw.endsWith('\0')) throw new Error('SOURCE19_CI_DIFF_TRUNCATED');
  const changed = raw === '' ? [] : raw.slice(0,-1).split('\0');
  const required = source19NativeCiRequired(changed);
  await fs.appendFile(process.env.GITHUB_OUTPUT,'required='+String(required)+'\n');
  console.log('SOURCE19_NATIVE_CI_SCOPE_'+(required?'REQUIRED':'NOT_REQUIRED'));
}
if (import.meta.url.startsWith('file:') && process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { await main(); }
  catch { console.error('SOURCE19_NATIVE_CI_SCOPE_REFUSED');process.exitCode=1; }
}
