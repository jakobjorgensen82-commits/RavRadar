import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import {
  assertRavScorePublicBrowserClosure,
  computeRavScorePublicBrowserClosure,
} from './lib/ravscore-public-browser-closure.mjs';
import { ravScoreModelBinding } from '../js/core/ravscore-model-contract.js';
import { ravScoreModelBinding as candidateBinding }
  from './rollback-assets/ravscore-model-contract.js';
import {
  computeSealedPublicImplementationClosureIdentity,
  parseSealedRavScoreBundleModule,
} from './verify-ravscore-operational-pages-deployment.mjs';

const baseline = await computeRavScorePublicBrowserClosure();
assertRavScorePublicBrowserClosure(baseline.manifest);
assert.ok(baseline.manifest.files.some(item => item.path === 'js/services/protected-runtime-envelope.js'),
  'the public admin closure must include its protected runtime envelope decoder');
assert.ok(!baseline.manifest.files.some(item => item.path === 'js/services/runtime-diagnostics-archive.js'),
  'the retired diagnostics-named path must not remain in the public browser closure');
const [integratedContractText, integratedBundleText] = await Promise.all([
  fs.readFile('js/core/ravscore-model-contract.js', 'utf8'),
  fs.readFile('js/core/ravscore-model-bundle.generated.js', 'utf8'),
]);
const integratedIdentity = computeSealedPublicImplementationClosureIdentity({
  expectedModel: 'integrated',
  expectedBinding: ravScoreModelBinding(),
  expectedContractText: integratedContractText,
  expectedBundleText: integratedBundleText,
  expectedPublicClosure: baseline.manifest,
});
assert.match(integratedIdentity.implementationClosureSha256, /^[a-f0-9]{64}$/,
  'the actual integrated bundle must seal against the actual public browser closure');
const sha256 = value => crypto.createHash('sha256').update(value).digest('hex');
const canonical = value => Array.isArray(value) ? value.map(canonical)
  : value && typeof value === 'object'
    ? Object.fromEntries(Object.keys(value).sort().map(key => [key, canonical(value[key])])) : value;
const seal = (manifest, model, baseBinding = ravScoreModelBinding()) => {
  const binding = { ...baseBinding, modelBundleSha256:
    sha256(JSON.stringify(model === 'integrated' ? canonical(manifest) : manifest)) };
  const text = [
    '// Generated by synthetic manifest contract fixture.',
    `export const GENERATED_RAVSCORE_MODEL_CONTRACT_SHA256 = '${binding.modelContractSha256}';`,
    `export const GENERATED_RAVSCORE_MODEL_BUNDLE_SHA256 = '${binding.modelBundleSha256}';`,
    `export const GENERATED_RAVSCORE_MODEL_BUNDLE_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 2)});`,
    '',
  ].join('\n');
  return { text, binding };
};
const actualNumerical = parseSealedRavScoreBundleModule(integratedBundleText,
  { model: 'integrated', binding: ravScoreModelBinding() });
const candidateBundleText = await fs.readFile('scripts/rollback-assets/ravscore-model-bundle.generated.js', 'utf8');
const actualCandidate = parseSealedRavScoreBundleModule(candidateBundleText,
  { model: 'candidate-g', binding: candidateBinding() });
const actualOptions = {
  expectedModel: 'integrated', expectedBinding: ravScoreModelBinding(),
  expectedContractText: integratedContractText, expectedBundleText: integratedBundleText,
  expectedPublicClosure: baseline.manifest,
};
if (actualNumerical.numerical) {
  assert.equal(actualCandidate.numerical, true);
  assert(!actualNumerical.manifest.files.some(row => row.path === 'js/services/rav-assistant.js'),
    'the separate app closure must not be forced back into the numerical identity');
  assert.throws(() => computeSealedPublicImplementationClosureIdentity({ ...actualOptions,
    expectedContractText: `${integratedContractText}\n// different wrapper\n`,
  }), /contract source differs from the public browser closure/);
  for (const [file, reason] of [
    ['js/core/ravscore-model-identity.generated.js', /numerical model identity differs/],
    ['js/core/ravscore-numerical-contract.js', /numerical model contract source differs/],
    ['js/core/ravscore-candidate-g-calculation.js', /model and public browser closures diverge/],
  ]) {
    const changed = structuredClone(baseline.manifest);
    const row = changed.files.find(item => item.path === file);
    assert(row, `actual public numerical dependency is present: ${file}`);
    row.sha256 = 'f'.repeat(64);
    assert.throws(() => computeSealedPublicImplementationClosureIdentity({ ...actualOptions,
      expectedPublicClosure: changed,
    }), reason);
  }
  const missingAppConsumer = structuredClone(baseline.manifest);
  missingAppConsumer.files = missingAppConsumer.files.filter(row => row.path !== 'js/services/rav-assistant.js');
  assert.throws(() => computeSealedPublicImplementationClosureIdentity({ ...actualOptions,
    expectedPublicClosure: missingAppConsumer,
  }), /public browser closure omits js\/services\/rav-assistant/);
  assert.throws(() => computeSealedPublicImplementationClosureIdentity({ ...actualOptions,
    expectedModel: 'candidate-g', expectedBinding: candidateBinding(), expectedBundleText: candidateBundleText,
  }), /numerical model identity differs/,
  'a valid C numerical bundle must not turn an I browser implementation into a Candidate-G deployment');
  for (const [mutate, reason] of [
    [manifest => manifest.excludedModules.push('js/core/ravscore-numerical-contract.js'), /self-identity exclusions/],
    [manifest => manifest.entrypoints.push('unbound-numerical-input.js'), /unbound entrypoint/],
    [manifest => { manifest.files = manifest.files.filter(row => row.path !== 'js/core/ravscore-numerical-contract.js'); }, /executable model contract source/],
  ]) {
    const changed = structuredClone(actualNumerical.manifest); mutate(changed);
    const synthetic = seal(changed, 'integrated');
    assert.throws(() => parseSealedRavScoreBundleModule(synthetic.text,
      { model: 'integrated', binding: synthetic.binding }), reason);
  }
}
// The older manifest still owns its contract and four consumer rows. The new
// numerical scope is not an exception for missing legacy implementation input.
for (const model of ['integrated', 'candidate-g']) {
  const contractPath = model === 'integrated' ? 'js/core/ravscore-model-contract.js'
    : 'scripts/rollback-assets/ravscore-model-contract.js';
  const fileKey = model === 'integrated' ? 'path' : 'file';
  const required = ['js/core/best-time-selector.js', 'js/core/local-zone-score.js',
    'js/services/rav-assistant.js', 'js/services/trip-evidence-public-adapter.js'];
  const manifest = {
    schemaVersion: model === 'integrated' ? '1.0.0' : 'candidate-g-operational-rollback-bundle-v1',
    normalizationId: model === 'integrated' ? 'lexer-esm-relative-import-closure-utf8-lf-static-cachebuster-v2'
      : 'candidate-g-rollback-lexer-esm-closure-utf8-lf-static-cachebuster-v2',
    ...(model === 'integrated' ? { contractSha256: ravScoreModelBinding().modelContractSha256 } : {}),
    entrypoints: required,
    ...(model === 'candidate-g' ? { excludedModules: ['js/core/ravscore-model-contract.js'] } : {}),
    files: [...required, contractPath].map(file => ({ [fileKey]: file, sha256: 'a'.repeat(64) })),
  };
  const positive = seal(manifest, model, model === 'integrated' ? ravScoreModelBinding() : candidateBinding());
  assert.equal(parseSealedRavScoreBundleModule(positive.text, { model, binding: positive.binding }).numerical, false);
  for (const [removed, reason] of [[contractPath, /executable model contract source/],
    [required[0], /omits public browser closure file/]]) {
    const changed = structuredClone(manifest);
    changed.files = changed.files.filter(row => row[fileKey] !== removed);
    const negative = seal(changed, model, positive.binding);
    assert.throws(() => parseSealedRavScoreBundleModule(negative.text,
      { model, binding: negative.binding }), reason);
  }
  assert.throws(() => parseSealedRavScoreBundleModule(`${positive.text}globalThis.extra = true;\n`,
    { model, binding: positive.binding }), /executable extra syntax/);
}
for (const file of [
  'app.js',
  'bootstrap.js',
  'service-worker.js',
  'js/ui/admin-active-ravscore.js',
]) {
  const source = await fs.readFile(file, 'utf8');
  const changed = await computeRavScorePublicBrowserClosure({
    sourceOverrides: new Map([[file, `${source}\n// public-artifact-mutation\n`]]),
  });
  assert.notEqual(changed.publicBrowserClosureSha256, baseline.publicBrowserClosureSha256,
    `${file} must be bound by the separate public browser closure`);
}
const bootstrap = await fs.readFile('bootstrap.js', 'utf8');
await assert.rejects(() => computeRavScorePublicBrowserClosure({
  sourceOverrides: new Map([[
    'bootstrap.js',
    `${bootstrap}\nconst hiddenModule = './evil.js'; void import(hiddenModule);\n`,
  ]]),
}), /non-literal or unparsed dynamic import/);
await assert.rejects(() => computeRavScorePublicBrowserClosure({
  sourceOverrides: new Map([[
    'bootstrap.js',
    `${bootstrap}\nvoid \`${'${import("./evil.js")}'}\`;\n`,
  ]]),
}), /cannot be resolved: bootstrap\.js -> \.\/evil\.js/);
const html = await fs.readFile('index.html', 'utf8');
const adminHtml = await fs.readFile('admin.html', 'utf8');
await assert.rejects(() => computeRavScorePublicBrowserClosure({
  sourceOverrides: new Map([['index.html', html.replace('<body>', '<body onload="import(\'./evil.js\')">')]]),
}), /unmodeled executable surface/);
await assert.rejects(() => computeRavScorePublicBrowserClosure({
  sourceOverrides: new Map([['index.html', html.replace("script-src 'self'", "script-src 'self' 'unsafe-inline' ")]]),
}), /same-origin script policy/);
assert.rejects(() => computeRavScorePublicBrowserClosure({
  sourceOverrides: new Map([['index.html', html.replace('src="bootstrap.js', 'src="evil.js')]]),
}), /exact bootstrap surface/);
await assert.rejects(() => computeRavScorePublicBrowserClosure({
  sourceOverrides: new Map([[
    'admin.html',
    adminHtml.replace('src="js/ui/admin-dashboard.js', 'src="js/ui/evil-admin.js'),
  ]]),
}), /exact bootstrap surface/);

console.log(`Public browser closure binds index/admin HTML, bootstrap/app/service-worker/admin model UI and ${baseline.manifest.files.length} transitive deployed modules independently of model identity.`);
